/* A stored key is either a bare id ("slag_bar") or the gear grammar
   ("slag_sword|rare|c17.42|+7"), whose base is the first field. Anything
   unrecognised comes back untouched: a key this map has never heard of is
   either already current or was never ours. */
export function moveKey(key) {
  if (typeof key !== "string" || !key) return key;
  const bar = key.indexOf("|");
  if (bar < 0) return MOVED_KEYS[key] || key;
  const base = key.slice(0, bar);
  const moved = MOVED_KEYS[base];
  return moved ? moved + key.slice(bar) : key;
}
