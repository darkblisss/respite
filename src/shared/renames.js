/* ============================================================
   Respite · renames.js · Where the old keys went
   ------------------------------------------------------------
   Names and ids used to be allowed to drift apart: RENAMED pinned
   a key while the name above it changed, so Gloam Ore answered to
   "cold" and Gnarl Wood to "iron". That bought safety and cost
   legibility, and every tool that rebuilt an id from a name -- the
   test harness did, quietly, for months -- got it wrong.

   Schema 12 closes the gap. An id is the first word of the name,
   always, and this map carries every key that moved on the day it
   closed. 386 of them.

   It is read once, by migrate12 in state.js, against a save that
   has not been opened since. Nothing else should need it: a key
   that still needs translating at runtime is a bug somewhere else.

   Renaming a material from here on means a new map and a new
   schema step. That is the point -- the cost is visible now.
   ============================================================ */

